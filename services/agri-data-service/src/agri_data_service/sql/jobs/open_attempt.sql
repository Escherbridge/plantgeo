-- open_attempt
-- Purpose: create the job_attempt row that records this worker's try at this shard, and return
--          its id so every later write can address it.
-- Loaded by: agri_data_service.jobs.lease
-- Params: work_item_id (uuid) -- the shard being attempted.
--         attempt_number (int) -- the shard's post-increment attempt_count, read straight back
--         out of the claim.
--         fencing_token (int) -- the token the claim just minted, copied onto the attempt.
--         worker_id (text) -- which worker process is running this attempt.
--
-- Parameter names appear above WITHOUT a leading colon. See "Header/bind-param trap" in
-- sql/AGENTS.md: SQLAlchemy scans comments for colon-prefixed words too.
--
-- What this returns: exactly one row, the new attempt's id. An attempt row is the audit record of
-- one worker's single try at one window -- when it started, when and how it ended, and what it
-- managed along the way.
--
-- WHY THE TWO NUMBERS ARE COPIED RATHER THAN COMPUTED HERE. attempt_number is set to the item's
-- post-increment attempt_count so that uq_job_attempt_item_number (which requires attempt numbers
-- to be unique per shard) and job_work_item.attempt_count can never disagree -- there is exactly
-- one source for the value and both columns read it. fencing_token is set to the item's
-- post-increment token so uq_job_attempt_item_fence is satisfied by construction: the token only
-- ever grows, is never reset on completion, and is therefore never reusable, so no two attempts
-- on one shard can ever collide on it.
--
-- How this query works, clause by clause:
--
--   INSERT INTO agri.job_attempt (...) VALUES (...)
--     A plain insert -- there is deliberately no conflict handling. A duplicate here would mean
--     two attempts sharing a number or a token on the same shard, which is a genuine invariant
--     break, and failing loudly is the correct response.
--
--   'running' as the status literal
--     The attempt's opening verdict. Every later close statement narrows on status = 'running',
--     so an attempt can only ever be closed once.
--
--   started_at = now()
--     The DATABASE clock, never the worker's, so attempts written by different containers remain
--     comparable to each other.
--
--   RETURNING id
--     RETURNING hands back a column from the row just inserted, in the same round trip. The id is
--     generated by the database, so this is the only way the worker learns which attempt it owns;
--     the caller treats a missing row as a hard error, because a claim without an attempt row has
--     no fenced identity to write anything else under.
INSERT INTO agri.job_attempt (job_work_item_id, attempt_number, fencing_token, status, worker_id, started_at)
VALUES (:work_item_id, :attempt_number, :fencing_token, 'running', :worker_id, now())
RETURNING id
